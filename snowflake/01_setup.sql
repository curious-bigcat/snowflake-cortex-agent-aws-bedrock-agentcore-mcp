/*
 * 01_setup.sql - Create database, schema, warehouse, and role for the ShopSmart demo.
 *
 * Run as ACCOUNTADMIN or a role with CREATE DATABASE / CREATE WAREHOUSE privileges.
 */

USE ROLE ACCOUNTADMIN;

-- Database and schema
CREATE DATABASE IF NOT EXISTS RETAIL_DEMO;
CREATE SCHEMA IF NOT EXISTS RETAIL_DEMO.ECOMMERCE;

-- Warehouse
CREATE WAREHOUSE IF NOT EXISTS RETAIL_DEMO_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 120
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Role
CREATE ROLE IF NOT EXISTS RETAIL_DEMO_ROLE;
GRANT USAGE ON DATABASE RETAIL_DEMO TO ROLE RETAIL_DEMO_ROLE;
GRANT ALL ON SCHEMA RETAIL_DEMO.ECOMMERCE TO ROLE RETAIL_DEMO_ROLE;
GRANT USAGE ON WAREHOUSE RETAIL_DEMO_WH TO ROLE RETAIL_DEMO_ROLE;

-- Cortex AI privileges
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE RETAIL_DEMO_ROLE;

-- Grant the role to the current user
GRANT ROLE RETAIL_DEMO_ROLE TO USER CURRENT_USER();

-- Set context
USE ROLE RETAIL_DEMO_ROLE;
USE DATABASE RETAIL_DEMO;
USE SCHEMA ECOMMERCE;
USE WAREHOUSE RETAIL_DEMO_WH;
